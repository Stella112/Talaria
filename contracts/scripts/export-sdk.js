// Generates packages/sdk/src/generated.ts from compiled artifacts and recorded deployments.
const { existsSync, readFileSync, writeFileSync } = require("node:fs");
const { resolve } = require("node:path");

const root = resolve(__dirname, "../..");
const names = ["TalariaUSD", "TalariaCore", "TalariaSubscriptions", "TalariaStreams", "TalariaChannels", "TalariaRemit", "MockUSDC", "TalariaLockbox", "TalariaLockboxV2", "TalariaProtect", "TalariaBridgeOut"];
const abi = (n) => JSON.parse(readFileSync(resolve(__dirname, `../artifacts/contracts/${n}.sol/${n}.json`), "utf8")).abi;
const records = (f) => {
  const file = resolve(root, "deployments", f);
  return existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : [];
};
const addresses = (list) => Object.fromEntries(list.map((r) => [r.name, r.address]));

let out = "// GENERATED by contracts/scripts/export-sdk.js. Do not edit.\n";
for (const n of names) out += `export const ${n}Abi = ${JSON.stringify(abi(n))} as const;\n`;
out += `export const portaldotDeployments: Record<string, \`0x\${string}\`> = ${JSON.stringify(addresses(records("portaldot-testnet.json")))} as any;\n`;
out += `export const baseSepoliaDeployments: Record<string, \`0x\${string}\`> = ${JSON.stringify(addresses(records("base-sepolia.json")))} as any;\n`;
writeFileSync(resolve(root, "packages/sdk/src/generated.ts"), out);
console.log("wrote packages/sdk/src/generated.ts");
